"""Rebuild js/risk-data.js from the positions in js/fund-data.js.

Run from the repository root:  python3 tools/refresh_risk.py

Run by the Saturday refresh after it has written js/fund-data.js, so the risk
figures always describe the same book the page shows. Prices come from Yahoo;
nothing here touches the brokerage account.

If prices cannot be fetched the existing js/risk-data.js is left exactly as
it was and the script exits non-zero, so a failed run never publishes a
half-built or empty risk block.
"""
import json
import os
import subprocess
import sys
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import risk_engine  # noqa: E402

FUND = os.path.join(ROOT, "js", "fund-data.js")
OUT = os.path.join(ROOT, "js", "risk-data.js")

HEADER = """/* ============================================
   GENERATED by tools/refresh_risk.py. Do not edit by hand.

   Risk of the stock positions in js/fund-data.js (options excluded), from
   daily prices over the window below. Volatilities are annualised; risk
   contributions are each position's share of the book's volatility and sum
   to 100%, with hedges negative. Correlations are pairwise on overlapping
   days, shrunk 25% toward the average and repaired to a valid matrix.
   ============================================ */

"""


def read_book():
    """The positions as the page sees them. fund-data.js is a JS literal,
    so let Node evaluate it rather than parse it by hand."""
    js = ("const fs=require('fs'),vm=require('vm');const c={};vm.createContext(c);"
          "vm.runInContext(fs.readFileSync(process.argv[1],'utf8')+';globalThis.__D=FUND_DATA;',c);"
          "const d=c.__D;process.stdout.write(JSON.stringify({asOf:d.asOf,"
          "longs:d.positions.longs,shorts:d.positions.shorts}));")
    out = subprocess.run(["node", "-e", js, FUND], capture_output=True, text=True, check=True)
    d = json.loads(out.stdout)
    book = ([{"ticker": p["ticker"], "side": "long", "pctNav": p["pctNav"]} for p in d["longs"]] +
            [{"ticker": p["ticker"], "side": "short", "pctNav": p["pctNav"]} for p in d["shorts"]])
    return d["asOf"], book


def main():
    as_of, book = read_book()
    try:
        risk = risk_engine.analyse_book(book)
    except RuntimeError as e:
        print(f"risk refresh failed, js/risk-data.js left unchanged: {e}", file=sys.stderr)
        return 1
    if risk["unpriced"] and len(risk["unpriced"]) > len(book) // 4:
        print(f"too many tickers unpriced, js/risk-data.js left unchanged: {risk['unpriced']}",
              file=sys.stderr)
        return 1

    risk = {"bookAsOf": as_of,
            "generatedAt": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
            **risk}
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(HEADER + "const RISK_DATA = " + json.dumps(risk, indent=4) + ";\n")

    p = risk["portfolio"]
    print(f"book {as_of}: {p['positions']} positions, vol {p['vol']}%, "
          f"diversification {p['diversificationRatio']}x, beta {p['betaToSPY']}")
    if risk["unpriced"]:
        print("unpriced:", risk["unpriced"])
    if risk["lowHistory"]:
        print("short history:", risk["lowHistory"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
